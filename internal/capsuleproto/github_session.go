const (
	gitCredentialHelper = "git-credential-github"
	githubTokenFile     = "github-token"
	githubBinDirectory  = "bin"
)

// gitCredentialHelperScript answers git's credential helper protocol for
// github.com. The token is read from a file the Station refreshes. This
// file never contains the token.
const gitCredentialHelperScript = `#!/bin/sh
# Answers git's credential helper protocol for github.com. The token is read
# from the file Meridian refreshes. This script does not contain the token.
if [ "$1" != "get" ]; then
  exit 0
fi
protocol=
host=
while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in
    protocol=https) protocol=yes ;;
    host=github.com|host=gist.github.com) host=yes ;;
    "") break ;;
  esac
done
token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)
if [ "$protocol" = "yes" ] && [ "$host" = "yes" ] && [ -n "$token" ]; then
  printf 'username=x-access-token\npassword=%s\n' "$token"
fi
`

// ghWrapperScript runs gh with the current token. A long session refreshes
// the file; the wrapper reads it on every invocation.
const ghWrapperScript = `#!/bin/sh
token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)
if [ -n "$token" ]; then
  GH_TOKEN=$token
  GITHUB_TOKEN=$token
  export GH_TOKEN GITHUB_TOKEN
fi
if [ -x /usr/local/bin/gh ]; then
  exec /usr/local/bin/gh "$@"
fi
echo "gh is not installed in this Capsule. Start a new Capsule from a current image." >&2
exit 127
`

// tokenVault is every installation token this Capsule has held. Output
// redaction reads it, including a token pushed in after the session started.
type tokenVault struct {
	mu     sync.Mutex
	tokens [][]byte
}

func (v *tokenVault) add(token string) {
	if token == "" {
		return
	}
	v.mu.Lock()
	defer v.mu.Unlock()
	raw := []byte(token)
	for _, existing := range v.tokens {
		if string(existing) == token {
			return
		}
	}
	v.tokens = append(v.tokens, raw)
	if len(v.tokens) > 64 {
		v.tokens = append([][]byte(nil), v.tokens[len(v.tokens)-64:]...)
	}
}

func (v *tokenVault) snapshot() [][]byte {
	if v == nil {
		return nil
	}
	v.mu.Lock()
	defer v.mu.Unlock()
	out := make([][]byte, len(v.tokens))
	copy(out, v.tokens)
	return out
}

// prepareSessionGit writes the pinned commit identity and, when the session
// has GitHub access, a credential helper and a gh wrapper that read the
// token file. The token is placed in the returned environment and in that
// file. The config and the helper do not contain it. A nil identity and no
// usable access leave env as it is.
func (s *Server) prepareSessionGit(
	identity *harnesssetup.GitIdentity, access *harnesssetup.GitHubAccess, env map[string]string,
) (map[string]string, error) {
	if identity != nil {
		s.rememberGitIdentity(identity)
	}
	github := access != nil && access.Usable()
	if !github {
		// Leave the token file alone. Another session in this Capsule may
		// still be using it. This session simply does not receive it.
		return s.prepareGitIdentity(identity, env)
	}
	if identity != nil && (identity.Name == "" || !harnesssetup.ValidGitIdentity(identity.Name, identity.Email)) {
		return nil, errors.New("invalid git identity")
	}
	base := s.config.HarnessHome
	if base == "" {
		base = "/home/capsule"
	}
	root, err := os.OpenRoot(base)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	if err := root.Mkdir(identityDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return nil, err
	}
	info, err := root.Lstat(identityDirectory)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() {
		return nil, errors.New("git identity directory is not a directory")
	}
	if err := root.Mkdir(identityDirectory+"/"+githubBinDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return nil, err
	}
	helperPath := filepath.Join(base, identityDirectory, gitCredentialHelper)
	tokenPath := filepath.Join(base, identityDirectory, githubTokenFile)
	if strings.Contains(helperPath, "'") || strings.Contains(tokenPath, "'") {
		return nil, errors.New("git credential helper path is unsafe")
	}
	script := strings.Replace(gitCredentialHelperScript, `token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)`,
		"token=$(cat "+shellQuote(tokenPath)+" 2>/dev/null || true)", 1)
	wrapper := strings.Replace(ghWrapperScript, `token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)`,
		"token=$(cat "+shellQuote(tokenPath)+" 2>/dev/null || true)", 1)
	if err := writeRootFile(root, identityDirectory+"/"+gitCredentialHelper, script, 0o700); err != nil {
		return nil, err
	}
	if err := writeRootFile(root, identityDirectory+"/"+githubBinDirectory+"/gh", wrapper, 0o700); err != nil {
		return nil, err
	}
	if err := writeRootFile(root, identityDirectory+"/"+githubTokenFile, access.Token+"\n", 0o600); err != nil {
		return nil, err
	}
	content := "# Generated by Meridian. Edits are replaced when a session starts.\n"
	if identity != nil {
		content = identity.Config()
	}
	content += githubCredentialConfig(helperPath)
	if err := writeRootFile(root, identityDirectory+"/gitconfig", content, 0o600); err != nil {
		return nil, err
	}
	if env == nil {
		env = map[string]string{}
	}
	env["GIT_CONFIG_GLOBAL"] = filepath.Join(base, identityDirectory, "gitconfig")
	env["GH_TOKEN"] = access.Token
	env["GITHUB_TOKEN"] = access.Token
	bin := filepath.Join(base, identityDirectory, githubBinDirectory)
	env["PATH"] = githubWrapperPath(env, bin)
	if s.githubTokens != nil {
		s.githubTokens.add(access.Token)
	}
	return env, nil
}

// prepareShellGit writes a git config for the workspace shell only. It does
// not replace the harness session's gitconfig, and it does not delete the
// token file when this shell has no GitHub access.
func (s *Server) prepareShellGit(identity *harnesssetup.GitIdentity, access *harnesssetup.GitHubAccess) (map[string]string, error) {
	github := access != nil && access.Usable()
	if identity == nil {
		identity = s.lastGitIdentity()
	}
	if identity == nil && !github {
		return nil, nil
	}
	base := s.config.HarnessHome
	if base == "" {
		base = "/home/capsule"
	}
	root, err := os.OpenRoot(base)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	if err := root.Mkdir(identityDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return nil, err
	}
	content := "# Generated by Meridian for the workspace shell.\n"
	if identity != nil && harnesssetup.ValidGitIdentity(identity.Name, identity.Email) && identity.Name != "" {
		content = identity.Config()
	}
	env := map[string]string{}
	if github {
		helperPath := filepath.Join(base, identityDirectory, gitCredentialHelper)
		tokenPath := filepath.Join(base, identityDirectory, githubTokenFile)
		if strings.Contains(helperPath, "'") || strings.Contains(tokenPath, "'") {
			return nil, errors.New("git credential helper path is unsafe")
		}
		if err := root.Mkdir(identityDirectory+"/"+githubBinDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
			return nil, err
		}
		script := strings.Replace(gitCredentialHelperScript, `token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)`,
			"token=$(cat "+shellQuote(tokenPath)+" 2>/dev/null || true)", 1)
		wrapper := strings.Replace(ghWrapperScript, `token=$(cat "$MERIDIAN_GITHUB_TOKEN_FILE" 2>/dev/null || true)`,
			"token=$(cat "+shellQuote(tokenPath)+" 2>/dev/null || true)", 1)
		if err := writeRootFile(root, identityDirectory+"/"+gitCredentialHelper, script, 0o700); err != nil {
			return nil, err
		}
		if err := writeRootFile(root, identityDirectory+"/"+githubBinDirectory+"/gh", wrapper, 0o700); err != nil {
			return nil, err
		}
		if err := writeRootFile(root, identityDirectory+"/"+githubTokenFile, access.Token+"\n", 0o600); err != nil {
			return nil, err
		}
		content += githubCredentialConfig(helperPath)
		env["GH_TOKEN"] = access.Token
		env["GITHUB_TOKEN"] = access.Token
		bin := filepath.Join(base, identityDirectory, githubBinDirectory)
		env["PATH"] = githubWrapperPath(env, bin)
		if s.githubTokens != nil {
			s.githubTokens.add(access.Token)
		}
	}
	if err := writeRootFile(root, identityDirectory+"/shell-gitconfig", content, 0o600); err != nil {
		return nil, err
	}
	env["GIT_CONFIG_GLOBAL"] = filepath.Join(base, identityDirectory, "shell-gitconfig")
	return env, nil
}

// githubWrapperPath prepends the gh wrapper directory to a PATH that is
// already set, then to this process's PATH. The default is only the fallback
// when both are empty, so an image PATH such as a harness pack's bin
// directory stays on the shell.
func githubWrapperPath(env map[string]string, bin string) string {
	path := ""
	if env != nil {
		path = env["PATH"]
	}
	if path == "" {
		path = os.Getenv("PATH")
	}
	if path == "" {
		path = "/usr/local/bin:/usr/bin:/bin"
	}
	return bin + ":" + path
}

func (s *Server) rememberGitIdentity(identity *harnesssetup.GitIdentity) {
	if identity == nil || identity.Name == "" {
		return
	}
	s.gitIdentityMu.Lock()
	copy := *identity
	s.gitIdentity = &copy
	s.gitIdentityMu.Unlock()
}

func (s *Server) lastGitIdentity() *harnesssetup.GitIdentity {
	s.gitIdentityMu.Lock()
	defer s.gitIdentityMu.Unlock()
	if s.gitIdentity == nil {
		return nil
	}
	copy := *s.gitIdentity
	return &copy
}

// refreshGitHubToken replaces the token file and remembers the token for
// redaction. The App private key never arrives here.
func (s *Server) refreshGitHubToken(token string) error {
	access := &harnesssetup.GitHubAccess{Token: token}
	if !access.Usable() {
		return errors.New("invalid github token")
	}
	base := s.config.HarnessHome
	if base == "" {
		base = "/home/capsule"
	}
	root, err := os.OpenRoot(base)
	if err != nil {
		return err
	}
	defer root.Close()
	if err := root.Mkdir(identityDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return err
	}
	if err := writeRootFile(root, identityDirectory+"/"+githubTokenFile, token+"\n", 0o600); err != nil {
		return err
	}
	if s.githubTokens != nil {
		s.githubTokens.add(token)
	}
	access.Wipe()
	return nil
}

func githubCredentialConfig(helperPath string) string {
	quoted := "!'" + helperPath + "'"
	var b strings.Builder
	for _, raw := range []string{"https://github.com", "https://gist.github.com"} {
		b.WriteString("[credential \"" + raw + "\"]\n")
		b.WriteString("\thelper =\n")
		b.WriteString("\thelper = " + quoted + "\n")
	}
	return b.String()
}

func shellQuote(path string) string {
	return "'" + strings.ReplaceAll(path, "'", "") + "'"
}

func writeRootFile(root *os.Root, name, content string, mode fs.FileMode) error {
	suffix := make([]byte, 16)
	if _, err := rand.Read(suffix); err != nil {
		return err
	}
	temp := name + ".tmp-" + hex.EncodeToString(suffix)
	f, err := root.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	_, writeErr := f.WriteString(content)
	closeErr := f.Close()
	if writeErr != nil || closeErr != nil {
		_ = root.Remove(temp)
		return errors.Join(writeErr, closeErr)
	}
	if err := root.Rename(temp, name); err != nil {
		_ = root.Remove(temp)
		return err
	}
	return nil
}

// applyGitHubEnv drops any GitHub token inherited from the Capsule process
// and, when access is usable, sets the session token.
func applyGitHubEnv(env []string, access *harnesssetup.GitHubAccess) []string {
	result := make([]string, 0, len(env)+2)
	for _, item := range env {
		key, _, _ := strings.Cut(item, "=")
		if key == "GH_TOKEN" || key == "GITHUB_TOKEN" {
			continue
		}
		result = append(result, item)
	}
	if access != nil && access.Usable() {
		result = append(result, "GH_TOKEN="+access.Token, "GITHUB_TOKEN="+access.Token)
	}
	return result
}

// clearGitHubEnv drops the session token from a setup map after it has been
// copied into the child environment.
func clearGitHubEnv(env map[string]string) {
	delete(env, "GH_TOKEN")
	delete(env, "GITHUB_TOKEN")
}
