const gitCredentialHelper = "git-credential"

// gitCredentialHelperScript answers git's credential helper protocol for
// github.com. The token is read from GH_TOKEN. This file never contains it.
const gitCredentialHelperScript = `#!/bin/sh
# Answers git's credential helper protocol for github.com. The token is read
# from GH_TOKEN and is not stored in this file.
if [ "$1" != "get" ]; then
  exit 0
fi
host=
while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in
    host=github.com|host=gist.github.com) host=yes ;;
    "") break ;;
  esac
done
if [ "$host" = "yes" ] && [ -n "${GH_TOKEN-}" ]; then
  printf 'username=x-access-token\npassword=%s\n' "$GH_TOKEN"
fi
`

// prepareSessionGit writes the pinned commit identity and, when the session
// has GitHub access, a credential helper that reads GH_TOKEN (ADR 0061).
// The token is placed in the returned environment and is not written to the
// config or the helper. A nil identity and no usable access leave env as it
// is. The laptop's git config is never sent.
func (s *Server) prepareSessionGit(
	identity *harnesssetup.GitIdentity, access *harnesssetup.GitHubAccess, env map[string]string,
) (map[string]string, error) {
	github := access != nil && access.Usable()
	if identity == nil && !github {
		return env, nil
	}
	if identity != nil && (identity.Name == "" || !harnesssetup.ValidGitIdentity(identity.Name, identity.Email)) {
		return nil, errors.New("invalid git identity")
	}
	base := s.config.HarnessHome
	if base == "" {
		base = "/home/capsule"
	}
	root, err := os.OpenRoot(base)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	if err := root.Mkdir(identityDirectory, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return nil, err
	}
	info, err := root.Lstat(identityDirectory)
	if err != nil {
		return nil, err
	}
	if !info.IsDir() {
		return nil, errors.New("git identity directory is not a directory")
	}
	helperPath := filepath.Join(base, identityDirectory, gitCredentialHelper)
	if strings.Contains(helperPath, "'") {
		return nil, errors.New("git credential helper path is unsafe")
	}
	content := "# Generated by Meridian. Edits are replaced when a session starts.\n"
	if identity != nil {
		content = identity.Config()
	}
	if github {
		if err := writeRootFile(root, identityDirectory+"/"+gitCredentialHelper, gitCredentialHelperScript, 0o700); err != nil {
			return nil, err
		}
		content += githubCredentialConfig(helperPath)
	}
	if err := writeRootFile(root, identityDirectory+"/gitconfig", content, 0o600); err != nil {
		return nil, err
	}
	if env == nil {
		env = map[string]string{}
	}
	env["GIT_CONFIG_GLOBAL"] = filepath.Join(base, identityDirectory, "gitconfig")
	if github {
		env["GH_TOKEN"] = access.Token
		env["GITHUB_TOKEN"] = access.Token
	} else {
		delete(env, "GH_TOKEN")
		delete(env, "GITHUB_TOKEN")
	}
	return env, nil
}

func githubCredentialConfig(helperPath string) string {
	quoted := "!'" + helperPath + "'"
	var b strings.Builder
	for _, url := range []string{"https://github.com", "https://gist.github.com"} {
		b.WriteString("[credential \"" + url + "\"]\n")
		b.WriteString("\thelper =\n")
		b.WriteString("\thelper = " + quoted + "\n")
	}
	return b.String()
}

func writeRootFile(root *os.Root, name, content string, mode fs.FileMode) error {
	suffix := make([]byte, 16)
	if _, err := rand.Read(suffix); err != nil {
		return err
	}
	temp := name + ".tmp-" + hex.EncodeToString(suffix)
	f, err := root.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	_, writeErr := f.WriteString(content)
	closeErr := f.Close()
	if writeErr != nil || closeErr != nil {
		_ = root.Remove(temp)
		return errors.Join(writeErr, closeErr)
	}
	if err := root.Rename(temp, name); err != nil {
		_ = root.Remove(temp)
		return err
	}
	return nil
}

// applyGitHubEnv drops any GitHub token inherited from the Capsule process
// and, when access is usable, sets the session token. The inherited value is
// not the owner's connection.
func applyGitHubEnv(env []string, access *harnesssetup.GitHubAccess) []string {
	result := make([]string, 0, len(env)+2)
	for _, item := range env {
		key, _, _ := strings.Cut(item, "=")
		if key == "GH_TOKEN" || key == "GITHUB_TOKEN" {
			continue
		}
		result = append(result, item)
	}
	if access != nil && access.Usable() {
		result = append(result, "GH_TOKEN="+access.Token, "GITHUB_TOKEN="+access.Token)
	}
	return result
}

// clearGitHubEnv drops the session token from a setup map after it has been
// copied into the child environment.
func clearGitHubEnv(env map[string]string) {
	delete(env, "GH_TOKEN")
	delete(env, "GITHUB_TOKEN")
}

// sessionGitHubToken is the token a start request carried, or empty when
// the request did not grant GitHub access. The request field is cleared so
// a later dump of the struct does not include it.
func sessionGitHubToken(access *harnesssetup.GitHubAccess) string {
	if access == nil || !access.Usable() {
		if access != nil {
			access.Wipe()
		}
		return ""
	}
	token := access.Token
	access.Wipe()
	return token
}
