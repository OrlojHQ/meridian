package harnesssetup

import (
	"strings"
	"unicode/utf8"
)

// GitIdentity is a commit author's name and email, and nothing else from a
// git config (ADR 0049). The daemon sends the identity a Capsule pinned, and
// capsuled writes it as a generated [user] section.
type GitIdentity struct {
	Name  string `json:"name"`
	Email string `json:"email"`
}

// ValidGitIdentity reports whether a commit identity is safe to store and to
// write as a quoted value in a generated [user] section. Both parts are set
// or both are empty. Control characters, quotes, backslashes, and the angle
// brackets that delimit a commit author are refused rather than escaped, so a
// quoted value can never end early.
func ValidGitIdentity(name, email string) bool {
	if (name == "") != (email == "") {
		return false
	}
	if len(name) > 320 || len(email) > 320 || !utf8.ValidString(name+email) {
		return false
	}
	for _, r := range name + email {
		if r < 0x20 || r == 0x7f || (r >= 0x80 && r < 0xa0) || r == ' ' || r == ' ' {
			return false
		}
	}
	if strings.ContainsAny(name+email, "\"\\<>") {
		return false
	}
	return strings.TrimSpace(name) == name && strings.TrimSpace(email) == email
}

// Config renders the identity as a git config file with one [user] section
// and quoted values. It is only called on a valid, non-empty identity.
func (identity GitIdentity) Config() string {
	return "# Generated by Meridian from your workstation profile. Edits are replaced\n" +
		"# when a session starts.\n" +
		"[user]\n" +
		"\tname = \"" + identity.Name + "\"\n" +
		"\temail = \"" + identity.Email + "\"\n"
}
